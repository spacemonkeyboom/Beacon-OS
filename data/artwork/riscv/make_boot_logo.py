# Beacon: turn RISC-V International's official stacked White & Yellow logo
# (unmodified, only scaled) composited on Berkeley Blue into a small
# run-length-encoded image for the riscv64 EFI boot loader.
# Usage: make_boot_logo.py <logo.png> <width> <out.h>
import sys
from PIL import Image
src, width, out = sys.argv[1], int(sys.argv[2]), sys.argv[3]
BLUE = (0x00, 0x32, 0x62)
logo = Image.open(src).convert('RGBA')
h = round(logo.size[1] * width / logo.size[0])
logo = logo.resize((width, h), Image.LANCZOS)
img = Image.new('RGB', logo.size, BLUE)
img.paste(logo, (0, 0), logo)
pal = img.quantize(colors=32, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE)
colors = pal.getpalette()[:32 * 3]
px = list(pal.getdata())
runs = []
i = 0
while i < len(px):
    j = i
    while j < len(px) and px[j] == px[i] and j - i < 255:
        j += 1
    runs += [j - i, px[i]]
    i = j
with open(out, 'w') as f:
    f.write('/* Generated by data/artwork/riscv/make_boot_logo.py. Do not edit.\n'
            ' * RISC-V and the RISC-V logo are registered trademarks of RISC-V\n'
            ' * International; official logo file, unmodified (scaled only). */\n')
    f.write('static const uint32 kRiscvLogoWidth = %d, kRiscvLogoHeight = %d;\n' % (width, h))
    f.write('static const uint8 kRiscvLogoBackground[3] = {0x%02x, 0x%02x, 0x%02x};\n' % BLUE)
    f.write('static const uint8 kRiscvLogoPalette[%d] = {\n' % len(colors))
    f.write(',\n'.join('\t' + ', '.join('0x%02x' % c for c in colors[k:k + 12]) for k in range(0, len(colors), 12)))
    f.write('\n};\n')
    f.write('static const uint8 kRiscvLogoRuns[%d] = {\n' % len(runs))
    f.write(',\n'.join('\t' + ', '.join(str(v) for v in runs[k:k + 24]) for k in range(0, len(runs), 24)))
    f.write('\n};\n')
print(width, h, 'runs bytes', len(runs))
