# Beacon: writes a boot splash header in the format of Haiku's generate_boot_screen
# (24-bit BGR zlib rows + shared 8-bit palette + 8-bit zlib rows), reusing the icon
# image from an existing header. Usage:
#   gen_boot_splash.py <logo.png> <existing-header.h> <out-header.h>
import re, sys, zlib
from PIL import Image

logo_png, old_h, out_h = sys.argv[1:4]
src = open(old_h).read()

def arr(name):
    m = re.search(r'static (?:const )?uint8 %s\[\] = \{(.*?)\};' % name, src, re.S)
    return bytes(int(v, 0) for v in re.findall(r'0x[0-9a-fA-F]+|\d+', m.group(1)))
def num(name):
    return int(re.search(r'%s = (\d+);' % name, src).group(1))

LW, LH = num('kSplashLogoWidth'), num('kSplashLogoHeight')
IW, IH = num('kSplashIconsWidth'), num('kSplashIconsHeight')
old_logo = zlib.decompress(arr('kSplashLogo24BitCompressedImage'))
icons = zlib.decompress(arr('kSplashIcons24BitCompressedImage'))
assert len(old_logo) == LW * LH * 3 and len(icons) == IW * IH * 3
bg_bgr = old_logo[0:3]
bg = (bg_bgr[2], bg_bgr[1], bg_bgr[0])

logo = Image.open(logo_png).convert('RGBA')
assert logo.size == (LW, LH), logo.size
canvas = Image.new('RGB', (LW, LH), bg)
canvas.paste(logo, (0, 0), logo)
icons_img = Image.frombytes('RGB', (IW, IH), icons, 'raw', 'BGR')

def bgr_bytes(img):
    return img.tobytes('raw', 'BGR')

# shared 256-colour palette over both images
both = Image.new('RGB', (max(LW, IW), LH + IH), bg)
both.paste(canvas, (0, 0)); both.paste(icons_img, (0, LH))
pal_img = both.quantize(colors=256, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE)
pal = (pal_img.getpalette() + [0] * 768)[:768]
logo8 = canvas.quantize(palette=pal_img, dither=Image.Dither.NONE).tobytes()
icons8 = icons_img.quantize(palette=pal_img, dither=Image.Dither.NONE).tobytes()

def carr(data):
    c = zlib.compress(data, 9)
    lines = []
    for i in range(0, len(c), 12):
        lines.append('\t' + ''.join('%d, ' % b for b in c[i:i + 12]))
    return '\n'.join(lines)

px = {k: num(k) for k in ('kSplashLogoPlacementX', 'kSplashLogoPlacementY',
                          'kSplashIconsPlacementX', 'kSplashIconsPlacementY')}
o = ['// This file was generated by ~/beacon/tools/gen_boot_splash.py (Beacon),',
     '// in the format of the generate_boot_screen Haiku build tool.', '']
for k, v in px.items():
    o.append('static const int32 %s = %d;' % (k, v))
o.append('')
for base, w, h, img in (('kSplashLogo', LW, LH, canvas), ('kSplashIcons', IW, IH, icons_img)):
    o += ['static const uint16 %sWidth = %d;' % (base, w),
          'static const uint16 %sHeight = %d;' % (base, h),
          '#ifndef __BOOTSPLASH_KERNEL__',
          'static uint8 %s24BitCompressedImage[] = {' % base, carr(bgr_bytes(img)), '};',
          '#endif', '']
o += ['#ifndef __BOOTSPLASH_KERNEL__', 'static const uint8 k8BitPalette[] = {']
for i in range(256):
    o.append('\t0x%x, 0x%x, 0x%x,' % tuple(pal[i * 3:i * 3 + 3]))
o += ['\t};', '']
for base, data in (('kSplashLogo', logo8), ('kSplashIcons', icons8)):
    o += ['static uint8 %s8BitCompressedImage[] = {' % base, carr(data), '};', '']
o += ['#endif', '']
open(out_h, 'w').write('\n'.join(o))
print('background', bg, 'logo', LW, LH, 'icons', IW, IH)
